import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');

async function read(rel) {
  return fs.readFile(path.join(ROOT, rel), 'utf8');
}

test('every DOM id used by the VR client exists in vr.html', async () => {
  const [html, main] = await Promise.all([read('web-src/vr.html'), read('web-src/vr-main.js')]);
  const ids = new Set([...html.matchAll(/id="([^"]+)"/g)].map((m) => m[1]));
  const used = new Set([...main.matchAll(/\$\('#([A-Za-z0-9_-]+)'\)/g)].map((m) => m[1]));
  assert.ok(used.size > 20, `expected many element lookups, found ${used.size}`);
  const missing = [...used].filter((id) => !ids.has(id));
  assert.deepEqual(missing, [], `vr-main.js references missing DOM ids: ${missing.join(', ')}`);
});

test('VR client imports resolve to real exports in the shared interaction engine', async () => {
  const engine = await read('src/core/vr-interaction.mjs');
  const exports = new Set([
    ...[...engine.matchAll(/export (?:function|const|class) ([A-Za-z0-9_]+)/g)].map((m) => m[1]),
    ...[...engine.matchAll(/export \{([^}]+)\}/g)].flatMap((m) => m[1].split(',').map((s) => s.trim())),
  ]);
  for (const file of ['web-src/vr-editor.js', 'web-src/vr-main.js', 'src/core/operations.mjs', 'src/core/world-agent.mjs']) {
    const src = await read(file);
    const block = src.match(/import\s*\{([^}]*)\}\s*from\s*'\.\.?\/?(?:src\/core\/)?vr-interaction\.mjs'/);
    if (!block) continue;
    const names = block[1].split(',').map((s) => s.trim()).filter(Boolean);
    assert.ok(names.length > 0);
    for (const name of names) {
      assert.ok(exports.has(name), `${file} imports "${name}", which vr-interaction.mjs does not export`);
    }
  }
});

test('Quest 3S controls are documented in the VR HTML help strip', async () => {
  const html = await read('web-src/vr.html');
  for (const hint of ['L-Stick', 'R-Stick', 'Trigger', 'Grip', 'B/Y', 'menu']) {
    assert.ok(html.includes(hint), `missing control hint: ${hint}`);
  }
  for (const id of ['vr-oslocomotion', 'rng-move-speed', 'sel-turn-mode', 'chk-teleport', 'sel-grid-snap', 'chk-snap']) {
    if (id === 'vr-oslocomotion') continue; // documentation-only marker
    assert.ok(html.includes(`id="${id}"`), `control missing: ${id}`);
  }
});

test('built VR bundle (when present) references the hashed entry', async (t) => {
  // `web/` is generated by `npm run build` and git-ignored; skip on a clean checkout.
  let html;
  try {
    html = await read('web/vr.html');
  } catch {
    t.skip('web/ not built yet (run npm run build)');
    return;
  }
  const match = html.match(/assets\/vr\.[0-9a-f]{10}\.js/);
  assert.ok(match, 'web/vr.html must reference a hashed VR bundle');
  const bundle = await fs.readFile(path.join(ROOT, 'web', match[0]), 'utf8');
  assert.ok(bundle.length > 10000, 'VR bundle looks empty');
  assert.ok(/2ce8c4/i.test(bundle), 'theme colour missing from bundle');
  // Phase 1–3 behaviours must survive bundling/minification
  for (const needle of ['modelstudio.vrSettings', 'world.snap', 'world.duplicate']) {
    assert.ok(bundle.includes(needle), `bundle is missing "${needle}"`);
  }
});
